function tx(g,s,x,y,col){
  g.fillStyle = col; s = String(s).toUpperCase(); let cx = x;
  for(const ch of s){
    const gl = FONT[ch] || FONT['?'];
    for(let r=0;r<6;r++){ const v = gl[r]; if(!v) continue;
      for(let c=0;c<4;c++) if(v & (8>>c)) g.fillRect(cx+c, y+r, 1, 1); }
    cx += 5;
  }
  return cx - x;
}
function txW(s){ return String(s).length*5; }
function wrap(s,max){
  const out=[]; let cur='';
  for(const w of String(s).split(/\s+/)){
    if(!w) continue;
    const t = cur ? cur+' '+w : w;
    if(t.length<=max) cur=t; else { if(cur) out.push(cur); cur = w.length>max ? w.slice(0,max) : w; }
  }
  if(cur) out.push(cur);
  return out;
}
function mkPages(list){
  const out=[];
  for(const it of list){
    if(typeof it !== 'string'){ out.push(it); continue; }
    const L = wrap(it,30);
    for(let i=0;i<L.length;i+=3) out.push({lines:L.slice(i,i+3)});
  }
  return out;
}
