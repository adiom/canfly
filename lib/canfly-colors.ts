/**
 * Небо одних суток: полдень → закат → ночь → предрассветный час.
 * Порядок здесь несёт время, а не перебирает палитру, поэтому задан вручную.
 * Часы рядом — это привязка к `era` каждого цвета, по ним выбирается стартовый кадр.
 */
const SKY_ARC: { id: string; hour: number }[] = [
  { id: 'CF-010', hour: 12 }, // macroscope — высота 10 000 м, без облаков
  { id: 'CF-002', hour: 15 }, // canfly — рэлеевское рассеяние, 445 нм
  { id: 'CF-012', hour: 17 }, // Aye
  { id: 'CF-011', hour: 19 }, // Au The
  { id: 'CF-001', hour: 20 }, // antred — архейский закат
  { id: 'CF-009', hour: 21 }, // deepsleep — 21:30
  { id: 'CF-015', hour: 3 }, //  Sleedy — 03:00, пустое шоссе
  { id: 'CF-007', hour: 5 }, //  sey2sky — 05:23, час до голубого
]

export const SKY_COLORS: CanflyColor[] = SKY_ARC.map((step) =>
  CANFLY_COLORS.find((color) => color.id === step.id),
).filter((color): color is CanflyColor => Boolean(color))

/** Ближайший к текущему часу кадр неба — по круглым сутками, а не по прямой. */
export function skyIndexForHour(hour: number): number {
  let bestIndex = 0
  let bestDistance = 24

  SKY_ARC.forEach((step, index) => {
    const direct = Math.abs(hour - step.hour)
    const distance = Math.min(direct, 24 - direct)
    if (distance < bestDistance) {
      bestDistance = distance
      bestIndex = index
    }
  })

  return bestIndex
}
